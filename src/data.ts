// Normalize and clean string for comparison or header matching
const normalizeHeader = (header: string): string => {
  return header
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // Remove Vietnamese accents
    .replace(/[^\w\s]/gi, '') // Remove special characters
    .replace(/\s+/g, ''); // Remove spaces
};

export function parseCSVToNguoiCoCong(parsedRows: any[]): NguoiCoCong[] {
  return parsedRows
    .map((row, idx) => {
      // Find matching keys dynamically
      let hoTen = '';
      let namSinh = '';
      let dienChinhSach = '';
      let tinhTrang = 'Còn sống';
      let diaChi = '';
      let lat = 0;
      let lng = 0;
      let thongTinGiaDinh = '';
      let tieuSuThanhTich = '';
      let hinhAnh = '';
      let namDuLieu = '';

      Object.keys(row).forEach((key) => {
        const norm = normalizeHeader(key);
        const value = String(row[key] || '').trim();

        if (norm === 'hoten' || norm === 'hovaten' || norm === 'hotennguoicocong') {
          hoTen = value;
        } else if (norm === 'namsinh' || norm === 'namsinhnguoicocong') {
          namSinh = value;
        } else if (norm === 'dienchinhsach' || norm === 'doituong' || norm === 'loaidienchinhsach') {
          dienChinhSach = value;
        } else if (norm === 'tinhtrang' || norm === 'trangthai') {
          tinhTrang = value;
        } else if (norm === 'diachi' || norm === 'diachithuongtru') {
          diaChi = value;
        } else if (norm === 'toadolat' || norm === 'vido' || norm === 'latitude' || norm === 'lat') {
          lat = parseFloat(value) || 0;
        } else if (norm === 'toadolng' || norm === 'kinhdo' || norm === 'longitude' || norm === 'lng') {
          lng = parseFloat(value) || 0;
        } else if (norm === 'thongtingiadinh' || norm === 'nguoithanthongtin' || norm === 'nguoichamsoc') {
          thongTinGiaDinh = value;
        } else if (norm === 'tieusuvathanhtich' || norm === 'tieusu' || norm === 'thanhtich') {
          tieuSuThanhTich = value;
        } else if (norm === 'hinhanh' || norm === 'anh' || norm === 'anhchandung' || norm === 'urlanh') {
          hinhAnh = value;
        } else if (norm === 'namdulieu' || norm === 'nam' || norm === 'namky' || norm === 'ngaythangnam' || norm === 'ngaycapnhat') {
          namDuLieu = value;
        }
      });

      // If key names don't match, try to map index based standard headers
      // (1: Họ tên, 2: Năm sinh, 3: Diện chính sách, 4: Tình trạng, 5: Địa chỉ, 6: Lat, 7: Lng, 8: Gia đình, 9: Tiểu sử, 10: Hình ảnh)
      const values = Object.values(row);
      if (!hoTen && values[0]) hoTen = String(values[0]).trim();
      if (!namSinh && values[1]) namSinh = String(values[1]).trim();
      if (!dienChinhSach && values[2]) dienChinhSach = String(values[2]).trim();
      if (!tinhTrang && values[3]) tinhTrang = String(values[3]).trim();
      if (!diaChi && values[4]) diaChi = String(values[4]).trim();
      if (!lat && values[5]) lat = parseFloat(String(values[5])) || 0;
      if (!lng && values[6]) lng = parseFloat(String(values[6])) || 0;
      if (!thongTinGiaDinh && values[7]) thongTinGiaDinh = String(values[7]).trim();
      if (!tieuSuThanhTich && values[8]) tieuSuThanhTich = String(values[8]).trim();
      if (!hinhAnh && values[9]) hinhAnh = String(values[9]).trim();
      if (values[10] && (!namDuLieu || namDuLieu === '')) namDuLieu = String(values[10]).trim();

      return {
        id: `csv-${idx}-${Date.now()}`,
        hoTen,
        namSinh,
        dienChinhSach: dienChinhSach || 'Chưa phân loại',
        tinhTrang: tinhTrang || 'Còn sống',
        diaChi: diaChi || 'Chưa cập nhật địa chỉ',
        lat,
        lng,
        thongTinGiaDinh: thongTinGiaDinh || 'Chưa cập nhật thông tin',
        tieuSuThanhTich: tieuSuThanhTich || 'Chưa cập nhật tiểu sử',
        hinhAnh: hinhAnh || '',
        namDuLieu: namDuLieu || new Date().toISOString().split('T')[0]
      };
    })
    .filter((item) => item.hoTen && item.lat && item.lng); // Must have at least name and valid coordinate
}
